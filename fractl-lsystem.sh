#!/bin/sh
set -e

esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

echo "FRACTL — describe your L-system (deterministic, context-free)."
echo "Symbols: F G draw, f moves without drawing, + - turn, [ ] save/restore the turtle."
echo

printf 'Axiom, e.g. F--F--F: '
read -r axiom
if [ -z "$axiom" ]; then
    echo "fractl-lsystem: an axiom is required"
    exit 2
fi

echo
echo "Rules, one per line as SYMBOL=replacement (e.g. F=F+F--F+F)."
echo "Blank line when you're done:"
rules=""
while :; do
    printf '  '
    read -r line
    [ -z "$line" ] && break
    sym=${line%%=*}
    rhs=${line#*=}
    if [ "$sym" = "$line" ] || [ -z "$sym" ] || [ ${#sym} -ne 1 ]; then
        echo "  (skipped — expected a single SYMBOL=replacement, e.g. F=F+F)"
        continue
    fi
    rules="$rules    $sym -> \"$(esc "$rhs")\";
"
done
if [ -z "$rules" ]; then
    echo "fractl-lsystem: at least one rule is required"
    exit 2
fi

printf 'Angle in degrees, e.g. 60: '
read -r angle
: "${angle:=60}"

printf 'Iterations, e.g. 4: '
read -r iterations
: "${iterations:=4}"

printf 'Step (units per forward move) [10]: '
read -r step
: "${step:=10}"

printf 'Starting heading in degrees [0]: '
read -r heading
: "${heading:=0}"

mkdir -p build
out="build/user_lsystem.fr"
cat > "$out" <<EOF
// Generated by fractl-lsystem.sh from plain-field input — a real, ordinary
// .fr program. Nothing downstream knows this wasn't hand-written.
fractal UserLSystem {
    axiom: "$(esc "$axiom")";

    rules {
$rules    }

    angle: $angle;
    iterations: $iterations;
    step: $step;
    start: (400, 400);
    heading: $heading;
}
EOF

echo
echo "== the .fr program this became =="
cat "$out"
echo

./fractl-run.sh "$out"
