
$ErrorActionPreference = "Stop"
$viewer = $PSScriptRoot
$data   = Join-Path $viewer "data"
$bundle = Join-Path $data "bundle.js"

if (-not (Test-Path $data)) { throw "viewer/data does not exist - run .\viewer\build_demos.ps1 first" }

$manifest = Join-Path $viewer "manifest.json"
if (-not (Test-Path $manifest)) { throw "viewer/manifest.json missing - run .\viewer\build_demos.ps1 first" }

function ConvertTo-JsString([string]$text) {
    ($text | ConvertTo-Json -Compress).Replace('</', '<\/')
}

$utf8 = New-Object System.Text.UTF8Encoding($false)
$sb   = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by viewer/pack.ps1 - do not edit. Regenerate after changing viewer/data.")
[void]$sb.AppendLine("window.FRACTL_BUNDLE = {")

$rows  = @()
$total = 0

function Add-Row($key, $path) {
    $script:total += (Get-Item $path).Length
    $text = [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8)
    $script:rows += ('  "{0}": {1}' -f $key, (ConvertTo-JsString $text))
}

Add-Row "manifest.json" $manifest

$assets = Get-ChildItem $data -File |
          Where-Object { $_.Name -ne "bundle.js" -and $_.Extension -in ".json", ".svg", ".ll" } |
          Sort-Object Name
foreach ($a in $assets) { Add-Row "data/$($a.Name)" $a.FullName }

[void]$sb.AppendLine(($rows -join ",`r`n"))
[void]$sb.AppendLine("};")

[System.IO.File]::WriteAllText($bundle, $sb.ToString(), $utf8)

$kb = [math]::Round((Get-Item $bundle).Length / 1KB, 1)
Write-Host "packed $($assets.Count + 1) files -> viewer/data/bundle.js ($kb KB)"
$assets | ForEach-Object { Write-Host ("   {0,-34} {1,8:N0} bytes" -f $_.Name, $_.Length) }
Write-Host "`nviewer/index.html now opens offline by double-click."
